def test_canonical_module_unit_level(tmp_path, monkeypatch):
    """Unit-level ledger behavior: record shape, idempotency, warm-up."""
    fake_home = tmp_path / "v310-canonical-home"
    path = fake_home / "hermes-router-canonical.jsonl"
    monkeypatch.setattr(canonical, "_store_path", lambda: str(path))
    canonical.clear_for_tests()
    try:
        assert canonical.commit_canonical_event("s9", "tm1", "DELIVERED", "rh1") is True
        # record exists for (session, refusal-hash); marker registered...
        assert canonical.commit_canonical_event("s9", "tm1", "DELIVERED-2", "rh1") is False
        # ...and on (session, content-hash)
        assert canonical.commit_canonical_event("s9", "tm1", "DELIVERED", "rh2") is False
        # different marker, same refusal: marker registered, no new record
        assert canonical.commit_canonical_event("s9", "tm2", "DELIVERED-3", "rh1") is False
        assert canonical.already_committed_for_turn("s9", "rh1", "tm2") is True
        # different session: new record
        assert canonical.commit_canonical_event("s10", "tm2", "DELIVERED", "rh3") is True
        with open(path, "r", encoding="utf-8") as fh:
            recs = [json.loads(line) for line in fh if line.strip()]
        assert len(recs) == 2
        assert recs[0]["delivery_mode"] == "own_turn"
        assert recs[0]["producer"] == "hermes-router"
        # warm-up from disk after in-memory reset
        canonical.clear_for_tests()
        assert canonical.already_committed_for_turn("s9", "rh1", "tm1") is True
        assert canonical.already_committed_for_turn("s9", "rhX", "tm1") is False
        assert canonical.has_refusal_record("s9", "rh1") is True
    finally:
        canonical.clear_for_tests()
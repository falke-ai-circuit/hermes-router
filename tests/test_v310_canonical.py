def _prime_post(session_id="s-can", model="minimax-m3"):
    state.stash_pending(session_id, model, ORIGINAL, "rendered-stub")
    state.set_last_user_msg_hash(session_id, state.hash_text(ORIGINAL))


def test_canonical_record_written_on_substitution(tmp_path, monkeypatch):
    _prime_post()
    monkeypatch.setattr(plugin.router, "call", lambda prompt, **k: RENDERED)
    out = plugin.on_transform_llm_output(
        response_text=REFUSAL, session_id="s-can", model="minimax-m3")
    assert out == RENDERED
    recs = _read_ledger(tmp_path)
    assert len(recs) == 1
    rec = recs[0]
    assert rec["session_id"] == "s-can"
    assert rec["producer"] == "hermes-router"
    assert rec["delivery_mode"] == "own_turn"
    assert rec["content_hash"] == canonical.hash_text(RENDERED)
    assert rec["original_refusal_hash"] == canonical.hash_text(REFUSAL)
    assert rec["turn_marker"]
    assert rec["committed_at"] > 0


def test_persisted_turn_rewritten_to_delivered_text(tmp_path, monkeypatch):
    _prime_post()
    # Seed the persisted split-brain state: flash turn already in state.db.

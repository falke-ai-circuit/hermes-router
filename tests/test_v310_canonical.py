def _read_ledger(tmp_path):
    """Read the test-scoped canonical sidecar (conftest isolation fixture
    redirects hermes_constants.get_hermes_home() to tmp_path/hermes-home)."""
    path = tmp_path / "v310-canonical-home" / "hermes-router-canonical.jsonl"
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


